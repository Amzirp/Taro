// ========== ОБЩИЕ ФУНКЦИИ ==========
function isValidDate(day, month, year) {
    if (!day || !month || !year) return false;
    if (day < 1 || day > 31) return false;
    if (month < 1 || month > 12) return false;
    if (year < 1900 || year > 2100) return false;
    
    const date = new Date(year, month - 1, day);
    return date.getDate() === day && date.getMonth() === month - 1;
}

function calculateBasicNumbers(day, month, year) {
    const first = sumDigits(day + month + year);
    const second = sumDigits(first);
    const firstDigitOfDay = parseInt(day.toString()[0]);
    let third = first - 2 * firstDigitOfDay;
    if (third < 0) third += 9;
    if (third === 0) third = 9;
    
    return {
        first: first,
        second: second,
        third: third,
        day: day,
        month: month,
        year: year
    };
}

function sumDigits(num) {
    let sum = num;
    while (sum > 9) {
        sum = sum.toString().split('').reduce((acc, digit) => acc + parseInt(digit), 0);
    }
    return sum;
}

function buildPythagorasMatrix(numbers) {
    const matrix = Array(9).fill(0);
    const allNumbers = [
        numbers.day, numbers.month, numbers.year,
        numbers.first, numbers.second, numbers.third
    ];
    
    allNumbers.forEach(num => {
        num.toString().split('').forEach(digit => {
            const d = parseInt(digit);
            if (d >= 1 && d <= 9) matrix[d-1]++;
        });
    });
    
    return matrix;
}

