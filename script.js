function createTarotReading(spreadType, question) {
    // Анализируем вопрос пользователя
    const questionCategory = analyzeQuestion(question);
    
    // Создаем копию колоды и перемешиваем
    const shuffledDeck = [...tarotDeck].sort(() => Math.random() - 0.5);
    const positions = getSpreadPositions(spreadType);
    
    // Берем нужное количество карт из перемешанной колоды
    const cards = shuffledDeck.slice(0, positions.length).map((card, index) => ({
        ...card,
        position: positions[index],
        // Выбираем значение карты в зависимости от категории вопроса
        selectedMeaning: card.meanings[questionCategory] || card.meanings.general,
        questionCategory: questionCategory
    }));
    
    return {
        question: question,
        spreadType: spreadType,
        cards: cards,
        questionCategory: questionCategory
    };
}

