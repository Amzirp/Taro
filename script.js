function calculateDestinyMatrix(day, month, year) {
    const energies = {
        personal: sumDigits(day),
        family: sumDigits(month),
        social: sumDigits(year),
        destiny: sumDigits(day + month + year),
        talents: sumDigits(day + month)
    };
    
    return {
        energies: energies,
        matrix: [
            [
                { number: energies.personal, label: 'Личное' },
                { number: energies.family, label: 'Семья' },
                { number: energies.social, label: 'Социум' },
                { number: energies.destiny, label: 'Судьба' }
            ],
            [
                { number: sumDigits(energies.personal + energies.family), label: 'Отношения' },
                { number: sumDigits(energies.family + energies.social), label: 'Наследство' },
                { number: sumDigits(energies.social + energies.destiny), label: 'Карьера' },
                { number: sumDigits(energies.destiny + energies.personal), label: 'Призвание' }
            ]
        ]
    };
}

