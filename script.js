// Анализ вопроса пользователя для определения категории
function analyzeQuestion(question) {
    const lowerQuestion = question.toLowerCase();
    
    // Ключевые слова для определения категории вопроса
    const loveKeywords = ['любовь', 'отношен', 'брак', 'семья', 'парень', 'девушка', 'муж', 'жена', 'встреч', 'свидан', 'роман', 'чувства'];
    const careerKeywords = ['работ', 'карьер', 'бизнес', 'деньги', 'зарплат', 'проект', 'начальник', 'коллег', 'должност', 'професси', 'финанс'];
    const healthKeywords = ['здоровье', 'болезнь', 'лечен', 'врач', 'боль', 'симптом', 'диагноз', 'анализ', 'операц', 'медицин', 'самочувств'];
    
    let loveScore = 0;
    let careerScore = 0;
    let healthScore = 0;
    
    loveKeywords.forEach(keyword => {
        if (lowerQuestion.includes(keyword)) loveScore++;
    });
    
    careerKeywords.forEach(keyword => {
        if (lowerQuestion.includes(keyword)) careerScore++;
    });
    
    healthKeywords.forEach(keyword => {
        if (lowerQuestion.includes(keyword)) healthScore++;
    });
    
    // Определяем доминирующую категорию
    const maxScore = Math.max(loveScore, careerScore, healthScore);
    
    if (maxScore === 0) return 'general';
    if (loveScore === maxScore) return 'love';
    if (careerScore === maxScore) return 'career';
    if (healthScore === maxScore) return 'health';
    
    return 'general';
}

